use serde::{Deserialize, Serialize};

use crate::models::evidence::EpistemicCategory;

/// Severity classification for potential inconsistencies or red flags.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum FindingSeverity {
    #[serde(rename = "LOW")]
    Low,
    #[serde(rename = "MEDIUM")]
    Medium,
    #[serde(rename = "HIGH")]
    High,
}

impl std::fmt::Display for FindingSeverity {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Low => write!(f, "LOW"),
            Self::Medium => write!(f, "MEDIUM"),
            Self::High => write!(f, "HIGH"),
        }
    }
}

/// Chronological event item in the narrative timeline.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct TimelineNarrativeItem {
    pub phase: String,
    pub description: String,
    pub evidence_id: String,
    pub evidence_type: EpistemicCategory,
}

/// A potential inconsistency, mistake, or operational red flag identified in the case.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct InconsistencyFinding {
    pub severity: FindingSeverity,
    pub finding: String,
    pub details: String,
    pub evidence_ref: String,
}

/// Fact or claim supporting the customer's dispute position.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct SupportingEvidenceItem {
    pub claim: String,
    pub source: String,
    pub evidence_id: String,
}

/// Fact or cryptographic proof contradicting the dispute (merchant defense).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ContradictingEvidenceItem {
    pub fact: String,
    pub source: String,
    pub evidence_id: String,
    /// Authoritatively verified by backend ledger checks; never delegated to LLM output.
    pub hash_verified: bool,
    pub epistemic_category: EpistemicCategory,
}

/// Explicit disclosure of unavailable evidence to prevent hallucination.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct MissingEvidenceDisclaimerItem {
    pub item: String,
    pub reason_unavailable: String,
}

/// Actionable recommendation for resolving or defending the dispute.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RecommendedActionItem {
    pub priority: u32,
    pub action: String,
    pub rationale: String,
}

/// Complete structured AI dispute investigation report.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct AIDisputeInvestigationReport {
    /// Authoritative PayPal Dispute ID.
    pub dispute_id: String,

    /// Associated purchase audit session ID (if correlated).
    pub session_id: Option<String>,

    /// ISO 8601 UTC timestamp of report generation.
    pub generated_at: String,

    /// Provider identifier (e.g. "gemini-3.8-flash" or "deterministic_fallback").
    pub provider: String,

    /// Explanatory note regarding provider status, fallback triggers, and privacy disclosures.
    pub provider_note: String,

    /// True if generated by Google Gemini; false if generated by deterministic fallback.
    pub is_ai_generated: bool,

    /// Whether the underlying cryptographic ledger verification succeeded (computed strictly by backend).
    pub ledger_hash_verified: bool,

    /// High-level executive summary of findings and dispute posture.
    pub executive_summary: String,

    /// Sequential timeline reconstructed from verified ledger events and PayPal records.
    pub narrative_timeline: Vec<TimelineNarrativeItem>,

    /// Inconsistencies, budget discrepancies, or operational flags.
    pub inconsistencies_or_red_flags: Vec<InconsistencyFinding>,

    /// Evidence points supporting the dispute claim.
    pub evidence_supporting_dispute: Vec<SupportingEvidenceItem>,

    /// Evidence points contradicting the dispute claim (merchant defense).
    pub evidence_contradicting_dispute: Vec<ContradictingEvidenceItem>,

    /// Explicitly declared unavailable evidence items.
    pub missing_evidence: Vec<MissingEvidenceDisclaimerItem>,

    /// Prioritized recommendations for the merchant or investigator.
    pub recommended_next_steps: Vec<RecommendedActionItem>,

    /// Authoritative evidence references cited and verified by the backend.
    pub valid_evidence_references: Vec<String>,

    /// Evidence references hallucinated or invalid that were discarded by the backend.
    pub discarded_unverified_references: Vec<String>,
}

/// Optional request payload for invoking the AI dispute investigator.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct AIInvestigationRequest {
    /// When set to true, bypasses the LLM API and forces the deterministic fallback engine.
    #[serde(default)]
    pub force_fallback: bool,
}

